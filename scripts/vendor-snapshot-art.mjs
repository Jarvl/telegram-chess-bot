#!/usr/bin/env node
// Writes the snapshot card's pictures as TypeScript modules, so the server needs no asset path at
// runtime (as scripts/vendor-pieces.mjs does for the pieces). Run again after changing a source;
// commit the output.
//
// - emoji.ts: the result badges' three Noto Color Emoji, from googlefonts/noto-emoji at a pinned
//   tag. Satori cannot draw colour-font glyphs, so the card places these as pictures instead.
// - flairEmoji.ts: every flair in the catalog as a Noto Color Emoji picture, keyed by flair id, for
//   the flair beside each player's name. Run again after adding a flair.
// - goatMark.ts: the Mini App's goat mark, for the bot's avatar and the brand footer.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
// Node strips the catalog's types; it has no runtime imports, so it loads without a build.
import { FLAIR } from '../packages/shared/src/flair/catalog.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const IMAGES = resolve(ROOT, 'apps/server/src/images');
/** Tag v2026-09-24-unicode18_0. */
const NOTO =
  'https://raw.githubusercontent.com/googlefonts/noto-emoji/e20cbc2bbec1926686be9f9bee7d1d2cfa1fea0e/2D/svg';
const EMOJI = { trophy: '1f3c6', skull: '1f480', scales: '2696' };

/**
 * Drops the XML declaration, the doctype and the editor's comments; the drawing itself is untouched.
 * Illustrator exports declare their namespaces as entities in the doctype, so those are substituted
 * first, and its private `i:aipgf` data (the file's editing state) is dropped.
 */
function clean(svg) {
  const start = svg.indexOf('<svg');
  if (start < 0 || !/viewBox="0 0 128 128"/.test(svg)) throw new Error('unexpected emoji svg');
  const entities = [...svg.slice(0, start).matchAll(/<!ENTITY\s+(\w+)\s+"([^"]*)">/g)];
  let body = svg.slice(start);
  for (const [, name, value] of entities) body = body.replaceAll(`&${name};`, value);
  if (/&(?!amp;|lt;|gt;|quot;|apos;|#)\w+;/.test(body)) throw new Error('undeclared entity');
  return body
    .replace(/<i:aipgf[\s\S]*?<\/i:aipgf>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/>\s+</g, '><')
    .trim();
}

/** Noto names a file by its codepoints in hex, joined by `_`, without variation selector 16. */
const notoCode = (emoji) =>
  [...emoji]
    .map((char) => char.codePointAt(0))
    .filter((point) => point !== 0xfe0f)
    .map((point) => point.toString(16))
    .join('_');

async function fetchEmoji(name, code) {
  const response = await fetch(`${NOTO}/emoji_u${code}.svg`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  return `  ${name}: ${JSON.stringify(clean(await response.text()))},`;
}

const emoji = [];
for (const [name, code] of Object.entries(EMOJI)) emoji.push(await fetchEmoji(name, code));
const flair = [];
for (const entry of FLAIR) flair.push(await fetchEmoji(entry.id, notoCode(entry.emoji)));
await writeFile(
  resolve(IMAGES, 'emoji.ts'),
  `// Generated by scripts/vendor-snapshot-art.mjs — do not edit by hand.
// Noto Color Emoji images by Google, used under the Apache License 2.0 (see ATTRIBUTION.md).
// Each entry is a whole 128 × 128 SVG.

export const EMOJI = {
${emoji.join('\n')}
} as const;
`,
);

await writeFile(
  resolve(IMAGES, 'flairEmoji.ts'),
  `// Generated by scripts/vendor-snapshot-art.mjs — do not edit by hand.
// Noto Color Emoji images by Google, used under the Apache License 2.0 (see ATTRIBUTION.md).
// Each entry is a whole 128 × 128 SVG of that flair's emoji, keyed by flair id.

export const FLAIR_EMOJI: Readonly<Record<string, string>> = {
${flair.join('\n')}
};
`,
);

const mark = await readFile(resolve(ROOT, 'apps/miniapp/src/assets/goat-mark.png'));
await writeFile(
  resolve(IMAGES, 'goatMark.ts'),
  `// Generated by scripts/vendor-snapshot-art.mjs from apps/miniapp/src/assets/goat-mark.png — do not
// edit by hand.

/** The Chess Goat mark, a square PNG. */
export const GOAT_MARK_PNG = ${JSON.stringify(`data:image/png;base64,${mark.toString('base64')}`)};
`,
);
console.log('wrote emoji.ts, flairEmoji.ts and goatMark.ts');
